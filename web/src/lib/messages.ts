/** 項目の表示名と上限（MSG-CMN-002、MSG-CMN-004 の {項目} と {n} に入れる）。 */
export const FIELDS: Record<string, { label: string; max?: number }> = {
  title: { label: 'タイトル', max: 200 },
  description: { label: '説明', max: 4000 },
  resultNote: { label: '結果コメント', max: 4000 },
  note: { label: 'メモ', max: 500 },
  body: { label: 'コメント', max: 2000 },
  name: { label: '名前', max: 50 },
  displayName: { label: '表示名', max: 50 },
  email: { label: 'メールアドレス', max: 254 },
  workDate: { label: '作業日' },
  minutes: { label: '作業時間' },
  conditions: { label: '条件', max: 4096 },
  verification: { label: '本人確認の方法', max: 200 },
  leaderUserId: { label: 'リーダー' },
  teamId: { label: 'チーム' },
  q: { label: 'キーワード', max: 100 },
};

export function messageText(id: string, params: Record<string, string | number> = {}): string {
  let text = MESSAGES[id] ?? id;
  for (const [key, value] of Object.entries(params)) {
    text = text.replaceAll(`{${key}}`, String(value));
  }
  return text;
}

/** 項目の誤りのメッセージ。{項目} と {n} は項目の表示名と上限で埋める。 */
export function fieldMessage(field: string, id: string, extra: Record<string, string | number> = {}): string {
  const base = field.replace(/\[\d+\]$/, '');
  const info = FIELDS[base];
  return messageText(id, { 項目: info?.label ?? base, n: info?.max ?? '', ...extra });
}
